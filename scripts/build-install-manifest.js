#!/usr/bin/env node
'use strict';

// Generates install-manifest.txt, the file list install.sh and uninstall.sh read
// instead of hand-kept COMMANDS/LIBS/HOOKS arrays. The curl path has no node, so
// the manifest is plain text a bash 3.2 `while read` loop can parse: a version
// line, then one filename (with its extension) per line under a [section].
//
// Retired sections list every file a previous manifest shipped that the tree no
// longer has. They are carried forward from the committed manifest and never
// pruned, so uninstall.sh can still remove a file an old release installed and
// install.sh can clean it up on upgrade.
//
//   node scripts/build-install-manifest.js          rewrite install-manifest.txt
//   node scripts/build-install-manifest.js --check  exit 1 if it is out of date
//
// test/install-manifest.test.js runs the --check comparison in CI.

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const MANIFEST_FILE = 'install-manifest.txt';
const FORMAT_LINE = '# slashdo install manifest v1';

// [section] -> source directory and which of its files ship. Lib entries keep
// their extension so a non-markdown lib asset needs no format change.
const KINDS = [
  { section: 'commands', dir: 'commands/do', ships: name => name.endsWith('.md') },
  { section: 'libs', dir: 'lib', ships: () => true },
  { section: 'hooks', dir: 'hooks', ships: name => name.endsWith('.js') },
];
const retired = section => `retired-${section}`;
const SECTIONS = KINDS.flatMap(({ section }) => [section, retired(section)]);

// Exactly what the shell scripts accept: a bare filename, never a path or dotfile.
const NAME_RE = /^[A-Za-z0-9_-][A-Za-z0-9._-]*$/;

function shippedFiles(root, { dir, ships }) {
  return fs.readdirSync(path.join(root, dir), { withFileTypes: true })
    .filter(entry => entry.isFile() && !entry.name.startsWith('.') && ships(entry.name))
    .map(entry => {
      if (!NAME_RE.test(entry.name)) {
        throw new Error(`${dir}/${entry.name}: the curl installer only accepts [A-Za-z0-9._-] filenames`);
      }
      return entry.name;
    });
}

function parseManifest(text) {
  const sections = Object.fromEntries(SECTIONS.map(name => [name, []]));
  let current = null;
  for (const raw of text.split('\n')) {
    const line = raw.replace(/\r$/, '');
    if (line === '' || line.startsWith('#')) continue;
    const header = line.match(/^\[(.+)\]$/);
    if (header) {
      if (!(header[1] in sections)) throw new Error(`${MANIFEST_FILE}: unknown section [${header[1]}]`);
      current = header[1];
    } else if (!current || !NAME_RE.test(line)) {
      throw new Error(`${MANIFEST_FILE}: unexpected line "${line}"`);
    } else {
      sections[current].push(line);
    }
  }
  return sections;
}

const sorted = names => [...new Set(names)].sort();

// The manifest the tree implies, given the previous manifest's text (or null).
function buildManifest(root = REPO_ROOT, previousText = null) {
  const previous = previousText === null ? null : parseManifest(previousText);
  const lines = [
    FORMAT_LINE,
    `# Generated by \`node scripts/build-install-manifest.js\` from commands/do/, lib/ and hooks/.`,
    '# Do not edit by hand. retired-* sections keep every file a past release shipped.',
  ];
  for (const kind of KINDS) {
    const current = sorted(shippedFiles(root, kind));
    const shipping = new Set(current);
    const gone = previous
      ? sorted([...previous[kind.section], ...previous[retired(kind.section)]]).filter(name => !shipping.has(name))
      : [];
    lines.push('', `[${kind.section}]`, ...current, '', `[${retired(kind.section)}]`, ...gone);
  }
  return `${lines.join('\n')}\n`;
}

function readCommitted(root = REPO_ROOT) {
  const file = path.join(root, MANIFEST_FILE);
  return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
}

if (require.main === module) {
  const committed = readCommitted();
  const expected = buildManifest(REPO_ROOT, committed);
  if (process.argv.includes('--check')) {
    if (committed !== expected) {
      process.stderr.write(`${MANIFEST_FILE} is out of date; run: node scripts/build-install-manifest.js\n`);
      process.exit(1);
    }
  } else if (committed !== expected) {
    fs.writeFileSync(path.join(REPO_ROOT, MANIFEST_FILE), expected);
    process.stdout.write(`updated ${MANIFEST_FILE}\n`);
  } else {
    process.stdout.write(`${MANIFEST_FILE} is up to date\n`);
  }
}

module.exports = { MANIFEST_FILE, FORMAT_LINE, SECTIONS, buildManifest, parseManifest, readCommitted };
